import { Router } from 'express';
import ExcelJS from 'exceljs';
import { z } from 'zod';
import { query } from '../db.js';
import { parse } from '../lib/errors.js';
import { assetCode } from '../lib/roles.js';
import { buildAssetFilter, STATUSES, ASSET_TYPES } from './assets.js';

const router = Router();

const STATUS_LABEL = {
  at_warehouse: 'At Warehouse', at_facility: 'At Facility', in_transit: 'In Transit', assigned_to_case: 'Assigned to Case',
  awaiting_receipt: 'Awaiting Receipt', overdue: 'Overdue', missing: 'Missing', under_investigation: 'Under Investigation',
  out_of_service: 'Out of Service',
};
const TYPE_LABEL = { tray: 'Tray', tote: 'Tote', implant_set: 'Implant Set', instrument_set: 'Instrument Set', loaner_kit: 'Loaner Kit', other: 'Other' };

// [header, key, width, numFmt]
const COLUMNS = [
  ['Asset ID', 'asset_code', 12], ['QR UUID', 'qr_value', 38], ['Reference', 'reference', 40], ['Type', 'source_type', 9],
  ['Asset Type', 'asset_type_label', 14], ['Description', 'description', 44], ['Status', 'status_label', 18],
  ['Team', 'team_name', 22], ['Current Facility', 'facility_name', 36], ['Assigned Representative', 'rep_name', 24],
  ['Last Known Custodian', 'custodian_name', 24], ['Agency', 'agency', 20], ['Warehouse (source)', 'source_warehouse', 22],
  ['Location (source)', 'source_location', 32], ['Lot', 'lot', 44], ['Catalog #', 'catalog_number', 14], ['Batch #', 'batch_number', 12],
  ['Serial #', 'serial_number', 9], ['Consignment Fee', 'consignment_fee', 14, '$#,##0.00'], ['Return Date', 'return_date', 12],
  ['Items', 'items_count', 7], ['Flags', 'flags', 22], ['Notes', 'notes', 44],
  ['Set Utilization Factor', 'set_utilization_factor', 12, '0.00'], ['Definition Value', 'definition_value', 14, '$#,##0.00'],
  ['Total Cases Last 12 Months', 'total_cases_12m', 12], ['Top HCP', 'top_hcp', 24], ['Top HCP Sales', 'top_hcp_sales', 14, '$#,##0.00'],
  ['Top HCP Cases', 'top_hcp_cases', 10], ['Days Since Last Case', 'days_since_last_case', 11], ['Utilization As Of', 'utilization_as_of', 12],
  ['Last Scanned', 'last_scanned_at', 18, 'yyyy-mm-dd hh:mm'], ['Last Transferred', 'last_transferred_at', 18, 'yyyy-mm-dd hh:mm'],
  ['Open Conflicts', 'open_conflicts', 10], ['Source Spreadsheets', 'sources', 40], ['Record Updated', 'updated_at', 18, 'yyyy-mm-dd hh:mm'],
];

const exportSchema = z.object({
  q: z.string().trim().max(200).optional(),
  status: z.enum(STATUSES).optional(),
  asset_type: z.enum(ASSET_TYPES).optional(),
  team_id: z.uuid().optional(),
  facility_id: z.uuid().optional(),
  rep_id: z.uuid().optional(),
  mine: z.enum(['1']).optional(),
  attention: z.enum(['1']).optional(),
});

router.get('/assets.xlsx', async (req, res) => {
  const f = parse(exportSchema, req.query);
  const { where, params } = buildAssetFilter(req.user, f);
  const { rows } = await query(
    `SELECT a.*, tm.name AS team_name, f.name AS facility_name, r.full_name AS rep_name, c.full_name AS custodian_name, q.qr_value,
            (SELECT count(*)::int FROM asset_conflicts ac WHERE ac.asset_id = a.id AND ac.status = 'open') AS open_conflicts,
            (SELECT string_agg(DISTINCT i.filename, ', ') FROM asset_field_sources s JOIN imports i ON i.id = s.import_id WHERE s.asset_id = a.id) AS sources
       FROM assets a
       LEFT JOIN facilities f ON f.id = a.current_facility_id
       LEFT JOIN users r ON r.id = a.assigned_rep_id
       LEFT JOIN users c ON c.id = a.custodian_id
       LEFT JOIN teams tm ON tm.id = a.team_id
       LEFT JOIN asset_qr_codes q ON q.asset_id = a.id AND q.active
      WHERE ${where}
      ORDER BY upper(a.reference), a.asset_no`, params);

  const wb = new ExcelJS.Workbook();
  wb.creator = 'Arthroplasty Asset Control';
  wb.created = new Date();
  const ws = wb.addWorksheet('Master Assets', { views: [{ state: 'frozen', ySplit: 1, xSplit: 3 }] });
  ws.columns = COLUMNS.map(([header, key, width, numFmt]) => ({ header, key, width, style: numFmt ? { numFmt } : {} }));
  for (const r of rows) {
    ws.addRow({
      ...r,
      asset_code: assetCode(r.asset_no),
      asset_type_label: TYPE_LABEL[r.asset_type],
      status_label: STATUS_LABEL[r.status],
      last_scanned_at: r.last_scanned_at || null,
      last_transferred_at: r.last_transferred_at || null,
    });
  }
  const header = ws.getRow(1);
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0A1424' } };
  header.alignment = { vertical: 'middle', wrapText: true };
  header.height = 30;
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: COLUMNS.length } };

  const info = wb.addWorksheet('Export Info');
  info.columns = [{ width: 22 }, { width: 60 }];
  info.addRows([
    ['Generated', new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC'],
    ['Generated by', req.user.full_name],
    ['Assets', rows.length],
    ['Filters', Object.entries(f).filter(([, v]) => v).map(([k, v]) => `${k}=${v}`).join(', ') || 'None (all visible assets)'],
    ['Note', 'Internal operational data. Contains no patient information.'],
  ]);
  info.getColumn(1).font = { bold: true };

  const stamp = new Date().toISOString().slice(0, 10);
  res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  res.setHeader('Content-Disposition', `attachment; filename="asset-master-${stamp}.xlsx"`);
  res.send(Buffer.from(await wb.xlsx.writeBuffer()));
});

export default router;
